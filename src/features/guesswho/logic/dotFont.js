export const DOT_COLS = 5
export const DOT_ROWS = 7

// Grille 7×5 de booléens pour un caractère (inconnu : grille éteinte).
export function glyph(ch) {
  const rows = GLYPHS[String(ch).toUpperCase()]
  return Array.from({ length: DOT_ROWS }, (_, r) => Array.from({ length: DOT_COLS }, (_, c) => rows?.[r]?.[c] === '#'))
}

export const hasGlyph = (ch) => String(ch).toUpperCase() in GLYPHS
